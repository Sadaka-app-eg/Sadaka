window.startAcademyQuizEngine = function(category, level) {
    let pool = [];

    // جمع الأسئلة المطابقة من كل جزء اختاره المستخدم
    window.selectedJuzList.forEach(juzName => {
        if (window.quranJuzQuizzes[juzName] && 
            window.quranJuzQuizzes[juzName][category] && 
            window.quranJuzQuizzes[juzName][category][level]) {
            
            const qList = window.quranJuzQuizzes[juzName][category][level];
            qList.forEach(q => {
                pool.push({ ...q, juz: juzName });
            });
        }
    });

    if (pool.length === 0) {
        alert("⚠️ عذراً! لم نضف أسئلة لهذا المستوى في الأجزاء المختارة بعد. جرب اختيار الجزء الأول أو تغيير المستوى.");
        return;
    }

    // دالة التدوير والخلط العشوائي للأسئلة
    pool.sort(() => Math.random() - 0.5);

    // اختيار 15 سؤالاً كحد أقصى لكل اختبار
    const selectedQuestions = pool.slice(0, 15);

    window.currentActiveQuranQuiz = {
        category: category,
        level: level,
        juzRangeText: window.selectedJuzList.length === 30 ? "المصحف كاملًا" : window.selectedJuzList.join('، '),
        questions: selectedQuestions,
        answers: new Array(selectedQuestions.length).fill(null)
    };

    window.renderAcademyQuizQuestionsHTML();
};

